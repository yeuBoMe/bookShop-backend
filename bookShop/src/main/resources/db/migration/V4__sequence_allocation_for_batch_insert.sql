-- =============================================================================
-- BookShop - Cho phep JDBC BATCH INSERT
--
-- Truoc: moi entity dung GenerationType.IDENTITY. Hibernate phai lay id sinh ra
--        cho TUNG dong nen TU TAT batching -> 5.000 dong = 5.000 lan round-trip,
--        du da bat hibernate.jdbc.batch_size.
-- Sau:   dung SEQUENCE + allocationSize = 50. Hibernate biet truoc id nen gom
--        duoc nhieu INSERT vao mot lan gui xuong DB.
--
-- allocationSize trong @SequenceGenerator PHAI bang INCREMENT cua sequence duoi day.
-- Lech nhau la sinh id trung. Doi mot ben thi phai doi ca hai.
--
-- Cot id van la GENERATED BY DEFAULT AS IDENTITY nen insert co id tuong minh
-- (do Hibernate cap) van hop le - khong can bo thuoc tinh identity.
-- =============================================================================

-- Dua sequence ve dung dinh cua du lieu hien co truoc, phong truong hop tung co
-- ban ghi duoc them bang id tuong minh (luc do sequence khong tu tang theo).
SELECT setval('public.books_id_seq',         COALESCE((SELECT MAX(id) FROM public.books), 1));
SELECT setval('public.categories_id_seq',    COALESCE((SELECT MAX(id) FROM public.categories), 1));
SELECT setval('public.orders_id_seq',        COALESCE((SELECT MAX(id) FROM public.orders), 1));
SELECT setval('public.order_details_id_seq', COALESCE((SELECT MAX(id) FROM public.order_details), 1));
SELECT setval('public.permissions_id_seq',   COALESCE((SELECT MAX(id) FROM public.permissions), 1));
SELECT setval('public.ratings_id_seq',       COALESCE((SELECT MAX(id) FROM public.ratings), 1));
SELECT setval('public.roles_id_seq',         COALESCE((SELECT MAX(id) FROM public.roles), 1));
SELECT setval('public.users_id_seq',         COALESCE((SELECT MAX(id) FROM public.users), 1));

-- Moi lan nextval cap mot khoi 50 id cho Hibernate dung dan.
-- Ke ca co nguoi insert bang SQL tay thi cung chi tao khoang trong id, khong sai du lieu.
ALTER SEQUENCE public.books_id_seq         INCREMENT BY 50;
ALTER SEQUENCE public.categories_id_seq    INCREMENT BY 50;
ALTER SEQUENCE public.orders_id_seq        INCREMENT BY 50;
ALTER SEQUENCE public.order_details_id_seq INCREMENT BY 50;
ALTER SEQUENCE public.permissions_id_seq   INCREMENT BY 50;
ALTER SEQUENCE public.ratings_id_seq       INCREMENT BY 50;
ALTER SEQUENCE public.roles_id_seq         INCREMENT BY 50;
ALTER SEQUENCE public.users_id_seq         INCREMENT BY 50;
